/**
 * Copy text to the clipboard. Uses the Clipboard API where available (HTTPS, localhost); otherwise
 * falls back to a hidden text area + execCommand, which still works on plain-HTTP previews and older
 * browsers. Resolves true when the text was copied.
 */
export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text)
      return true
    }
  } catch {
    // permission denied or not focused: try the fallback
  }
  const area = document.createElement('textarea')
  area.value = text
  area.setAttribute('readonly', '')
  area.style.position = 'fixed'
  area.style.opacity = '0'
  document.body.appendChild(area)
  area.select()
  try {
    return document.execCommand('copy')
  } catch {
    return false
  } finally {
    area.remove()
  }
}
